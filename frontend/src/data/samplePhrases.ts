const capitalize = (text: string) => text.charAt(0).toUpperCase() + text.slice(1);

// 64 репліки + 120 розповідних речень × (само собою + 7 вступних слів) ≈ 1024 фрази.
export const samplePhrases: SamplePhrase[] = [
  ...utterances.map(([category, text], index) => ({
    id: `phrase-${index + 1}`,
    text,
    category,
    group: `phrase-${index + 1}`,
  })),
  ...statements.flatMap(([category, clause], index) => {
    const group = `statement-${index + 1}`;
    // Крапку ставимо тут, а не в даних: те саме речення йде і самостійно, і після
    // вступного слова, тож у сідах лежить лише його тіло з малої літери.
    return [
      { id: group, text: `${capitalize(clause)}.`, category, group },
      ...openers.map((opener, openerIndex) => ({
        id: `${group}-${openerIndex + 1}`,
        text: `${opener} ${clause}.`,
        category,
        group,
      })),
    ];
  }),
];

export function getRandomSamplePhrase(previousId: string | null): SamplePhrase {
  const previous = previousId ? samplePhrases.find((phrase) => phrase.id === previousId) : undefined;
  // Виключаємо не саму фразу, а всю її групу: інакше кубик міг видати те саме
  // речення з іншим вступним словом, і це читалося б як повтор.
  const availablePhrases = previous
    ? samplePhrases.filter((phrase) => phrase.group !== previous.group)
    : samplePhrases;

  return availablePhrases[Math.floor(Math.random() * availablePhrases.length)];
}
